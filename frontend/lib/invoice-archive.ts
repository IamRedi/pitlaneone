import "server-only";

import { createHash } from "node:crypto";
import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import type { SupabaseClient } from "@supabase/supabase-js";
import { createXRechnungXml, type XRechnungInvoice } from "@/lib/xrechnung";

type JsonObject = Record<string, unknown>;
type SupabaseLike = SupabaseClient;

type ArchiveInvoice = {
  id: string;
  company_id: string;
  invoice_number: string | null;
  invoice_kind: string;
  lifecycle_status: string;
  currency: string;
  registration_country: string;
  issued_at: string;
  due_date: string | null;
  finalized_at: string;
  material_total: number | string;
  labor_total: number | string;
  net_amount: number | string;
  tax_rate: number | string;
  tax_amount: number | string;
  total_amount: number | string;
  invoice_snapshot: unknown;
};

function object(value: unknown): JsonObject {
  return value && typeof value === "object" && !Array.isArray(value) ? value as JsonObject : {};
}

function text(value: unknown, fallback = "") {
  return typeof value === "string" || typeof value === "number" ? String(value) : fallback;
}

function number(value: unknown) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : 0;
}

function safePdfText(value: string) {
  return value
    .replace(/[–—]/g, "-")
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/[^\u0009\u000A\u000D\u0020-\u00FF]/g, "?");
}

function wrap(font: PDFFont, value: string, size: number, maxWidth: number) {
  const words = safePdfText(value).split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (font.widthOfTextAtSize(candidate, size) <= maxWidth || !current) current = candidate;
    else { lines.push(current); current = word; }
  }
  if (current) lines.push(current);
  return lines.length ? lines : [""];
}

export async function createInvoiceArchivePdf(invoice: ArchiveInvoice) {
  const snapshot = object(invoice.invoice_snapshot);
  const issuer = object(snapshot.issuer);
  const client = object(snapshot.client);
  const vehicle = object(snapshot.vehicle);
  const service = object(snapshot.service);
  const items = Array.isArray(snapshot.items) ? snapshot.items.map(object) : [];
  const locale = invoice.registration_country === "AL" ? "sq-AL" : invoice.registration_country === "IT" ? "it-IT" : "de-DE";
  const money = (value: unknown) => number(value).toLocaleString(locale, { style: "currency", currency: invoice.currency });
  const date = (value: string | null) => value ? new Intl.DateTimeFormat(locale).format(new Date(`${value}T00:00:00Z`)) : "-";
  const title = invoice.invoice_kind === "storno" ? "STORNO / CANCELLATION" : "INVOICE / RECHNUNG";

  const pdf = await PDFDocument.create();
  pdf.setTitle(`${title} ${invoice.invoice_number ?? invoice.id}`);
  pdf.setSubject("Immutable invoice archive generated by PitlaneOne");
  pdf.setCreator("PitlaneOne");
  pdf.setProducer("PitlaneOne invoice archive");
  pdf.setCreationDate(new Date(invoice.finalized_at));
  pdf.setModificationDate(new Date(invoice.finalized_at));
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const width = 595.28;
  const height = 841.89;
  const margin = 46;
  let page: PDFPage;
  let y = 0;

  const newPage = () => {
    page = pdf.addPage([width, height]);
    y = height - margin;
    page.drawText("PITLANEONE - IMMUTABLE ARCHIVE COPY", { x: margin, y: 22, size: 7, font: regular, color: rgb(.42, .45, .5) });
  };
  const ensure = (needed: number) => { if (y - needed < 42) newPage(); };
  const draw = (value: string, x: number, size = 10, useBold = false, color = rgb(.08, .1, .14)) => {
    page.drawText(safePdfText(value), { x, y, size, font: useBold ? bold : regular, color });
  };
  const line = () => { page.drawLine({ start: { x: margin, y }, end: { x: width - margin, y }, thickness: .7, color: rgb(.78, .8, .84) }); y -= 12; };

  newPage();
  draw(title, margin, 17, true, rgb(.72, .29, .12));
  draw(invoice.invoice_number ?? invoice.id, 365, 15, true);
  y -= 26;
  draw(text(issuer.legal_name || issuer.display_name || issuer.company_name, "Workshop"), margin, 13, true);
  draw(`Issued: ${date(invoice.issued_at)}`, 365, 9);
  y -= 15;
  const issuerAddress = [text(issuer.address), text(issuer.city), text(issuer.country)].filter(Boolean).join(", ");
  if (issuerAddress) draw(issuerAddress, margin, 9);
  draw(`Due: ${date(invoice.due_date)}`, 365, 9);
  y -= 13;
  const issuerContact = [text(issuer.phone), text(issuer.email)].filter(Boolean).join(" / ");
  if (issuerContact) draw(issuerContact, margin, 9);
  y -= 13;
  if (issuer.tax_id) { draw(`Tax ID: ${text(issuer.tax_id)}`, margin, 9); y -= 12; }
  if (issuer.registration_number) { draw(`Registration: ${text(issuer.registration_number)}`, margin, 9); y -= 12; }
  y -= 5; line();

  draw("BILL TO", margin, 8, true, rgb(.42, .45, .5)); y -= 14;
  draw(`${text(client.first_name)} ${text(client.last_name)}`.trim() || "Customer", margin, 11, true); y -= 14;
  for (const addressLine of [text(client.billing_address), [text(client.billing_postal_code), text(client.billing_city)].filter(Boolean).join(" "), text(client.billing_country), text(client.phone)].filter(Boolean)) {
    draw(addressLine, margin, 9); y -= 12;
  }
  y -= 5;
  draw("VEHICLE / SERVICE", 315, 8, true, rgb(.42, .45, .5));
  y -= 14;
  draw(`${text(vehicle.model, "Vehicle")} ${text(vehicle.plate_number)}`.trim(), 315, 10, true); y -= 13;
  if (vehicle.vin) { draw(`VIN: ${text(vehicle.vin)}`, 315, 8); y -= 11; }
  draw(`Service: ${text(service.date, "-")} / ${number(service.km).toLocaleString(locale)} km`, 315, 8);
  y -= 18; line();

  draw("DESCRIPTION", margin, 8, true, rgb(.42, .45, .5));
  draw("QTY", 330, 8, true, rgb(.42, .45, .5));
  draw("MATERIAL", 382, 8, true, rgb(.42, .45, .5));
  draw("LABOUR", 462, 8, true, rgb(.42, .45, .5));
  y -= 13; line();
  for (const item of items) {
    const descriptionLines = wrap(regular, text(item.name, "Service item"), 9, 265);
    const rowHeight = Math.max(28, descriptionLines.length * 11 + 10);
    ensure(rowHeight + 15);
    descriptionLines.forEach((value, index) => page.drawText(value, { x: margin, y: y - index * 11, size: 9, font: regular, color: rgb(.08, .1, .14) }));
    draw(`${number(item.quantity || 1).toLocaleString(locale)} ${text(item.unit_label)}`, 330, 8);
    draw(money(item.material_cost), 382, 8);
    draw(money(number(item.labor_cost) * (1 - number(item.labor_discount_percent) / 100)), 462, 8);
    y -= rowHeight; line();
  }

  ensure(150);
  y -= 4;
  const totals: Array<[string, unknown, boolean]> = [
    ["Materials", invoice.material_total, false],
    ["Labour", invoice.labor_total, false],
    ["Net", invoice.net_amount, false],
    [`Tax (${number(invoice.tax_rate).toLocaleString(locale)}%)`, invoice.tax_amount, false],
    ["TOTAL", invoice.total_amount, true]
  ];
  for (const [label, value, strong] of totals) {
    draw(label, 340, strong ? 11 : 9, strong);
    draw(money(value), 465, strong ? 11 : 9, strong);
    y -= strong ? 18 : 14;
  }
  if (invoice.invoice_kind === "storno") {
    y -= 8;
    draw(`Cancels invoice ${text(snapshot.related_invoice_number, text(snapshot.related_invoice_id))}`, margin, 9, true, rgb(.65, .16, .16));
    y -= 13;
    for (const value of wrap(regular, `Reason: ${text(snapshot.cancellation_reason, "-")}`, 8, width - margin * 2)) {
      draw(value, margin, 8); y -= 10;
    }
  }
  if (issuer.bank_name || issuer.bank_iban) {
    y -= 8; draw(`Bank: ${[text(issuer.bank_name), text(issuer.bank_iban)].filter(Boolean).join(" / ")}`, margin, 8);
  }
  if (issuer.invoice_footer) {
    y -= 16;
    for (const value of wrap(regular, text(issuer.invoice_footer), 7, width - margin * 2)) { draw(value, margin, 7); y -= 9; }
  }

  return pdf.save({ useObjectStreams: false, addDefaultPage: false });
}

export async function archiveInvoicePdf(supabase: SupabaseLike, companyId: string, invoiceId: string) {
  const { data: existing } = await supabase.from("invoice_documents")
    .select("id, storage_path, sha256, original_filename, size_bytes")
    .eq("company_id", companyId).eq("invoice_id", invoiceId).eq("document_format", "pdf").maybeSingle();
  if (existing) return existing;

  const { data: invoice, error } = await supabase.from("invoices")
    .select("id, company_id, invoice_number, invoice_kind, lifecycle_status, currency, registration_country, issued_at, due_date, finalized_at, material_total, labor_total, net_amount, tax_rate, tax_amount, total_amount, invoice_snapshot")
    .eq("id", invoiceId).eq("company_id", companyId).maybeSingle();
  if (error || !invoice) throw new Error("Invoice could not be loaded for archiving.");

  const bytes = await createInvoiceArchivePdf(invoice as ArchiveInvoice);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const filename = `${String(invoice.invoice_number ?? invoice.id).replace(/[^a-z0-9_-]+/gi, "-")}.pdf`;
  const storagePath = `${companyId}/${invoiceId}/${sha256}.pdf`;
  const { error: uploadError } = await supabase.storage.from("invoice-archive").upload(storagePath, bytes, {
    contentType: "application/pdf",
    cacheControl: "31536000",
    upsert: false
  });
  if (uploadError && !String(uploadError.message ?? "").toLowerCase().includes("already exists")) {
    throw new Error("Invoice PDF could not be stored in the private archive.");
  }

  const { data: documentId, error: registerError } = await supabase.rpc("register_company_invoice_document", {
    input_company_id: companyId,
    input_invoice_id: invoiceId,
    input_document_format: "pdf",
    input_mime_type: "application/pdf",
    input_original_filename: filename,
    input_storage_path: storagePath,
    input_sha256: sha256,
    input_size_bytes: bytes.byteLength,
    input_document_standard: null,
    input_standard_version: null,
    input_validation_status: "not_applicable",
    input_validation_report: {}
  });
  if (registerError || !documentId) throw new Error("Invoice PDF was stored but could not be registered.");
  return { id: documentId, storage_path: storagePath, sha256, original_filename: filename, size_bytes: bytes.byteLength };
}

export async function archiveInvoiceXRechnung(supabase: SupabaseLike, companyId: string, invoiceId: string) {
  const { data: existing } = await supabase.from("invoice_documents")
    .select("id, storage_path, sha256, original_filename, size_bytes, document_standard, standard_version, validation_status")
    .eq("company_id", companyId).eq("invoice_id", invoiceId).eq("document_format", "xml").maybeSingle();
  if (existing) return existing;

  const { data: invoice, error } = await supabase.from("invoices")
    .select("id, invoice_number, invoice_kind, currency, issued_at, due_date, net_amount, tax_rate, tax_amount, total_amount, invoice_snapshot")
    .eq("id", invoiceId).eq("company_id", companyId).maybeSingle();
  if (error || !invoice) throw new Error("Invoice could not be loaded for XRechnung export.");

  const generated = createXRechnungXml(invoice as XRechnungInvoice);
  const sha256 = createHash("sha256").update(generated.bytes).digest("hex");
  const filename = `${String(invoice.invoice_number ?? invoice.id).replace(/[^a-z0-9_-]+/gi, "-")}-xrechnung.xml`;
  const storagePath = `${companyId}/${invoiceId}/${sha256}.xml`;
  const { error: uploadError } = await supabase.storage.from("invoice-archive").upload(storagePath, generated.bytes, {
    contentType: "application/xml",
    cacheControl: "31536000",
    upsert: false
  });
  if (uploadError && !String(uploadError.message ?? "").toLowerCase().includes("already exists")) {
    throw new Error("XRechnung XML could not be stored in the private archive.");
  }

  const { data: documentId, error: registerError } = await supabase.rpc("register_company_invoice_document", {
    input_company_id: companyId,
    input_invoice_id: invoiceId,
    input_document_format: "xml",
    input_mime_type: "application/xml",
    input_original_filename: filename,
    input_storage_path: storagePath,
    input_sha256: sha256,
    input_size_bytes: generated.bytes.byteLength,
    input_document_standard: generated.report.standard,
    input_standard_version: generated.report.version,
    input_validation_status: generated.report.validationStatus,
    input_validation_report: generated.report
  });
  if (registerError || !documentId) throw new Error("XRechnung XML was stored but could not be registered.");
  return {
    id: documentId,
    storage_path: storagePath,
    sha256,
    original_filename: filename,
    size_bytes: generated.bytes.byteLength,
    document_standard: generated.report.standard,
    standard_version: generated.report.version,
    validation_status: generated.report.validationStatus
  };
}
